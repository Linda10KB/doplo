local Celebration = {}
local historyKey = "celebration_history"
local legacyKey = "last_celebration"
local randomModulus = 2147483647

local function isValidRandomState(value)
    return type(value) == "number"
        and value == math.floor(value)
        and value >= 1
        and value < randomModulus
end

local function initialRandomState()
    -- Device entropy gives independent sequences even when two readers start
    -- at the same time. This never seeds KOReader's process-wide math.random.
    local entropyFile = io.open("/dev/urandom", "rb")
    if entropyFile then
        local bytes = entropyFile:read(4)
        entropyFile:close()
        if bytes and #bytes == 4 then
            local first, second, third, fourth = bytes:byte(1, 4)
            local seed = first * 16777216 + second * 65536 + third * 256 + fourth
            return seed % (randomModulus - 1) + 1
        end
    end

    -- Some desktop ports have no /dev/urandom. Mix wall time, CPU time and a
    -- fresh allocation's identity rather than giving them a fixed sequence.
    local entropy = tostring(os.time()) .. ":" .. tostring(os.clock()) .. ":" .. tostring({})
    local seed = 1
    for index = 1, #entropy do
        seed = (seed * 131 + entropy:byte(index)) % (randomModulus - 1)
    end
    return seed + 1
end

local function readHistory(settings)
    local saved = settings:readSetting(historyKey)
    local history = { version = 1, seen = {} }
    if type(saved) == "table" and saved.version == 1 then
        local savedSeen = type(saved.seen) == "table" and saved.seen or {}
        for _, compliment in ipairs(compliments) do
            if savedSeen[compliment] == true then
                history.seen[compliment] = true
            end
            if saved.last == compliment then
                history.last = compliment
            end
        end
        if isValidRandomState(saved.random_state) then
            history.random_state = saved.random_state
        end
        if history.last then
            history.seen[history.last] = true
        end
    else
        -- Older releases remembered only the previous message, not a complete
        -- history. Keep that known message out of the first new random round.
        local legacyIndex = settings:readSetting(legacyKey)
        if type(legacyIndex) == "number" and legacyIndex == math.floor(legacyIndex)
            and legacyIndex >= 1 and legacyIndex <= 16 then
            history.last = compliments[legacyIndex]
            history.seen[history.last] = true
        end
    end
    history.random_state = history.random_state or initialRandomState()
    return history
end

local function availableCompliments(history)
    local available = {}
    for _, compliment in ipairs(compliments) do
        if not history.seen[compliment] then
            available[#available + 1] = compliment
        end
    end
    if #available > 0 then
        return available
    end

    history.seen = {}
    -- A new round may have any order, but its first message cannot be the one
    -- just shown. The previous message remains available later in this round.
    for _, compliment in ipairs(compliments) do
        if compliment ~= history.last then
            available[#available + 1] = compliment
        end
    end
    return available
end

function Celebration.next(settings)
    local history = readHistory(settings)
    local available = availableCompliments(history)
    history.random_state = history.random_state * 48271 % randomModulus
    local index = 1 + math.floor(history.random_state / randomModulus * #available)
    local compliment = available[index]
    history.seen[compliment] = true
    history.last = compliment
    settings:saveSetting(historyKey, history):flush()
    return compliment
end

return Celebration
