-- Run from repository root: luajit tools/build_bank.lua > /tmp/doplo-bank.lua
-- Empty classic 8x8 searches are expensive; expect several minutes on a desktop.
package.path = "doplo.koplugin/?.lua;" .. package.path
local M, G, S, D = require("doplo/model"), require("doplo/generator"), require("doplo/solver"), require("doplo/difficulty")
local function emptyBank(kind, n)
    local cfg, random = M.config(kind, n), G.random(77213 + n * 13)
    local found, used = {}, {}
    for _ = 1, 15000 do
        local p = G.candidate(cfg, random, 0)
        p.prefilled = false
        local r = S.solve(p, nil, { workLimit = 600000 })
        local level = D.rate(r, p)
        if level and M.equal(r.solution, p.solution) then
            local sol, mask = G.encode(p)
            if not used[sol] then
                used[sol] = true
                found[#found + 1] = { sol, mask, level = level,
                    score = r.waves + 4 * math.log(r.nodes) / math.log(2) }
            end
        end
        if #found >= 160 then break end
    end
    table.sort(found, function(a, b) return a.score < b.score end)
    local byLevel = { Easy = {}, Medium = {}, Hard = {}, Expert = {} }
    for _, record in ipairs(found) do
        local bucket = byLevel[record.level]
        if #bucket < 12 then bucket[#bucket + 1] = record end
    end
    for _, level in ipairs(M.levels) do
        assert(#byLevel[level] == 12, "No empty bank coverage: " .. kind .. n .. level)
    end
    return byLevel
end
io.write("-- Generated by tools/build_bank.lua; original, individually certified puzzles.\nreturn {\n")
for _, kind in ipairs({ "classic", "plus" }) do
    io.write("  ", kind, " = {\n")
    for _, n in ipairs(M.sizes[kind]) do
        io.write("    [", n, "] = {\n")
        for _, mode in ipairs({ "prefilled", "empty" }) do
            local blank = mode == "empty" and emptyBank(kind, n)
            io.write("      ", mode, " = {\n")
            for j, level in ipairs(M.levels) do
                local records = blank and blank[level] or {}
                local random = G.random(20261117 + n * 713 + j * 991)
                local attempts, used = 0, {}
                while #records < 12 do
                    attempts = attempts + 1
                    assert(attempts < 30000, "No prefilled bank coverage: " .. kind .. n .. level)
                    local p = G.attempt(M.config(kind, n), level, random, { workLimit = 600000 })
                    if p then
                        local sol, mask = G.encode(p)
                        if not used[sol] then
                            records[#records + 1], used[sol] = { sol, mask }, true
                        end
                    end
                end
                io.write("        ", level, " = {\n")
                for _, record in ipairs(records) do
                    io.write(('          {"%s","%s"},\n'):format(record[1], record[2]))
                end
                io.write("        },\n")
                io.stderr:write(("%s %d %s %s: %d boards\n"):format(kind, n, mode, level, #records))
            end
            io.write("      },\n")
        end
        io.write("    },\n")
    end
    io.write("  },\n")
end
io.write("}\n")
