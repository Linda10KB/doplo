-- Run from repository root: luajit tools/build_bank.lua > doplo.koplugin/doplo/bank.lua
package.path = "doplo.koplugin/?.lua;" .. package.path
local M, G = require("doplo/model"), require("doplo/generator")
io.write("-- Generated by tools/build_bank.lua; original, individually certified puzzles.\nreturn {\n")
for _, kind in ipairs({ "classic", "plus" }) do
    for _, n in ipairs(M.sizes[kind]) do
        io.write("  [", n, "] = {\n")
        for j, level in ipairs(M.levels) do
            local random = G.random(20261117 + n * 713 + j * 991)
            local found, attempts, used = 0, 0, {}
            io.write("    ", level, " = {\n")
            while found < 12 do
                attempts = attempts + 1
                assert(attempts < 30000, "no bank coverage for " .. n .. " " .. level)
                local p = G.attempt(M.config(kind, n), level, random, { workLimit = 600000 })
                if p then
                    local s, g = G.encode(p)
                    if not used[s] then
                        io.write(('      {"%s","%s"},\n'):format(s, g))
                        used[s], found = true, found + 1
                    end
                end
            end
            io.stderr:write(("%s %d %s: %d boards, %d attempts\n"):format(kind, n, level, found, attempts))
            io.write("    },\n")
        end
        io.write("  },\n")
    end
end
io.write("}\n")
