-- Requires KOReader's JSON, filesystem, and fsync APIs.
require("setupkoenv")
package.path = assert(os.getenv("DOPLO_SOURCE")) .. "/doplo.koplugin/?.lua;" .. package.path
local Store = require("doplo/store")
local M, G, Game = require("doplo/model"), require("doplo/generator"), require("doplo/game")
local bank = require("doplo/bank")
local store = assert(Store.new(assert(os.getenv("KO_HOME")) .. "/test-games"))
local function write(path, bytes)
    local f = assert(io.open(path, "wb"))
    assert(f:write(bytes))
    assert(f:close())
end
local id = store:newId()
local g = Game.new(G.decode("plus", 12, "Hard", bank.plus[12].empty.Hard[1], false))
local i = g.selected
assert(store:save(id, g))
assert(g:edit(i, 8, true))
g.pencil = true
assert(store:save(id, g))
assert(g:edit(i, 0, false))
assert(g:travel(false))
assert(store:save(id, g))
local anotherProcess = Store.new(store.dir)
local restored = assert(anotherProcess:load(id))
assert(restored.notes[i] == 256 and restored.board[i] == -1 and restored.selected == i and restored.pencil)
assert(restored.cursor == 1 and #restored.history == 2 and restored:travel(true) and restored.board[i] == 0)
assert(M.equal(restored.p.solution, g.p.solution) and restored.p.prefilled == false)
print("PASS disk round trip including notes, history, cursor and puzzle")
write(store:path(id, "a"), "{")
local previous = assert(store:load(id))
assert(previous.revision == 2 and previous.notes[i] == 256 and #previous.history == 1)
write(store:path(id, "a"), '{"schema":99}')
assert(store:load(id).revision == 2)
write(store:path(id, "a") .. ".tmp", "unfinished")
assert(previous:edit(i, 1, false))
assert(store:save(id, previous))
assert(store:load(id).board[i] == 1)
print("PASS recovery after truncation, unknown schema and abandoned staging file")
local id2 = store:newId()
assert(id ~= id2 and not store:load("../wrong"))
assert(store:save(id2, Game.new(G.decode("classic", 5, "Easy", bank.classic[5].prefilled.Easy[1]))))
assert(#store:list() == 2 and store:load(id).p.n == 12 and store:load(id2).p.n == 5)
print("PASS two games, safe IDs and independent histories")
local lfs = require("libs/libkoreader-lfs")
local blocked = store:path(id, "b") .. ".tmp"
assert(lfs.mkdir(blocked))
assert(previous:edit(i, 2, false))
local before = previous.revision
assert(not store:save(id, previous) and previous.revision == before)
assert(store:load(id).board[i] == 1)
assert(lfs.rmdir(blocked) and store:save(id, previous))
assert(store:load(id).board[i] == 2)
print("PASS failed write preserves the last snapshot and retries successfully")
